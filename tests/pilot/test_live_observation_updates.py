def _engine_with_one_observation() -> tuple[DecisionEngine, dict]:
    observation = _fresh_observation_at("obs-a", 1.0, 1.1)
    return DecisionEngine(parameters(), MODEL_IDENTITY), {"obs-a": observation}


def test_each_specified_trigger_fires():
    cases = [
        (SceneStatus(signature=0.5, explicit_question="which branch?"), "explicit_question"),
        (SceneStatus(signature=0.5, map_conflict=True), "map_conflict"),
        (SceneStatus(signature=0.5, lost_targets=("t1",)), "lost_target"),
        (SceneStatus(signature=0.5, new_targets=("t2",)), "new_target"),
        (SceneStatus(signature=0.5, identity_ambiguity=True), "identity_ambiguity"),
        (SceneStatus(signature=0.5, horizon_s=1.0), "reduced_horizon"),
        (SceneStatus(signature=0.95), "signature_change"),
    ]
    for scene, expected in cases:
        engine, observations = _engine_with_one_observation()
        # One prior send establishes the deadband/silence/horizon history the
        # later rules compare against.
        primed = engine.consider(S(1.2), SceneStatus(signature=0.5, horizon_s=10.0), observations, 0, 0, None)
        assert primed.send
        decision = engine.consider(S(2.0), scene, observations, 0, 0, None)
        assert decision.send, f"{expected} did not fire"
        assert expected in decision.reason, f"{decision.reason} does not name {expected}"


def test_the_first_scene_is_sent_because_nothing_has_been_reviewed_yet():
    engine, observations = _engine_with_one_observation()
    decision = engine.consider(S(1.2), SceneStatus(signature=0.5), observations, 0, 0, None)
    assert decision.send and decision.reason == "initial_scene"


def test_deadband_suppresses_insignificant_repeats():
    engine, observations = _engine_with_one_observation()
    first = engine.consider(S(2.0), SceneStatus(signature=0.5), observations, 0, 0, None)
    assert first.send and first.reason == "initial_scene"
    tiny = engine.consider(S(2.5), SceneStatus(signature=0.53), observations, 0, 0, None)
    assert not tiny.send and tiny.reason == "no_trigger"
    significant = engine.consider(S(2.6), SceneStatus(signature=0.75), observations, 0, 0, None)
    assert significant.send and significant.reason == "signature_change"


def test_max_silence_forces_a_review_of_a_static_scene():
    engine, observations = _engine_with_one_observation()
    first = engine.consider(S(1.0), SceneStatus(signature=0.5), observations, 0, 0, None)
    assert first.send
    quiet = engine.consider(S(5.0), SceneStatus(signature=0.5), observations, 0, 0, None)
    assert not quiet.send
    forced = engine.consider(S(8.0), SceneStatus(signature=0.5), observations, 0, 0, None)
    assert forced.send and forced.reason == "max_silence"


def test_dedup_prevents_a_second_identical_request_within_the_freshness_window():
    engine, observations = _engine_with_one_observation()
    first = engine.consider(S(1.0), SceneStatus(signature=0.9, new_targets=("t",)), observations, 0, 0, None)
    assert first.send and first.reason == "new_target"
    second = engine.consider(S(1.5), SceneStatus(signature=0.9, new_targets=("t",)), observations, 0, 0, None)
    assert not second.send and second.reason == "deduplicated"
    # A different evidence requirement about the same subject is not a duplicate.
    third = engine.consider(S(1.6), SceneStatus(signature=0.9, lost_targets=("t",)), observations, 0, 0, None)
    assert third.send and third.reason == "lost_target"


