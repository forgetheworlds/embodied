def test_anticipatory_send_fires_as_the_boundary_approaches_and_supersedes():
    engine, observations = _engine_with_one_observation()
    primed = engine.consider(S(0.5), SceneStatus(signature=0.5, decision_boundary_s=30.0), observations, 0, 0, None)
