def _fresh_observation_at(record_id: str, capture_s: float, now_s: float) -> Observation:
    return make_observation(record_id, 0, int(capture_s * 1e9), int(now_s * 1e9))


def test_fresh_observation_mid_goal_reaches_the_configured_model():
    seam = SeamFixture()
    broker = PilotBroker(seam, parameters(), host_id=HOST, clock_id=CLOCK)
    broker.set_mission(mission_contract(), S(1.0))
    broker.set_goal(
        make_proposal("P0", "local", "fp-P0", 0, ("sel-x",), "explore"), S(1.2)
    )
    observation = _fresh_observation_at("obs-mid", 5.0, 5.1)
    broker.on_observation(observation, S(5.1))
    engine = DecisionEngine(parameters(), MODEL_IDENTITY)
    decision = engine.consider(
        S(5.2),
        SceneStatus(signature=0.9, new_targets=("red-object",)),
        broker.observations,
        0,
        broker.base_goal_revision,
        broker.outstanding_request,
    )
    assert decision.send and "new_target" in decision.reason
    assert decision.request is not None
    assert "obs-mid" in decision.request.observation_ids
    assert decision.request.model_identity == MODEL_IDENTITY
    config_text = RUNTIME_MODEL_CONFIG.read_text(encoding="utf-8")
    assert "opencode-go/deepseek-v4.1-flash" in config_text


