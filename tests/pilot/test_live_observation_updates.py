def _probe_config(tmp_path: Path, max_calls=None, spend_ceiling_usd=None) -> Path:
    import textwrap

    path = tmp_path / "runtime-model.yaml"
    path.write_text(
        textwrap.dedent(
            f"""
            model:
              provider: opencode-go
              id: {MODEL_IDENTITY}
              base_url: https://opencode.ai/zen/go/v1
              api: openai-completions
              image_transport: base64
              declared_input: [text, image]
            probe:
              max_calls: {max_calls if max_calls is not None else ''}
              spend_ceiling_usd: {spend_ceiling_usd if spend_ceiling_usd is not None else ''}
            pilot:
              event_deadband: 0.08
              max_silence_s: 6.0
              latency_budget_s: 2.5
              guard_margin_s: 1.0
              response_deadline_s: 4.0
              observation_freshness_s: 6.0
              retry_budget: 1
            """
        ).strip()
        + "\n",
        encoding="utf-8",
    )
    return path


