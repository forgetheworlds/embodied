class SeamFixture:
    """Final goal admission as a test double, with the frozen refusal tokens
    from the P03 plan and an audit of every call."""

    REFUSAL_TOKENS = (
        "stale_pose",
        "missing_depth",
        "frame_epoch_mismatch",
        "calibration_mismatch",
        "detector_unavailable",
        "unknown_geometry",
    )

    def __init__(self, refuse_with: str | None = None) -> None:
        self.refuse_with = refuse_with
        self.admit_calls: list[SpatialGoal] = []
        self.cancel_calls: list[tuple[str, int, str]] = []
        self.invalidations: dict[str, int] = {}
        self.queued_samples = 2
        self._counter = 0

    def admit(self, proposal: SpatialGoal, context: AdmissionContext) -> GoalStatus:
        self.admit_calls.append(proposal)
        if self.refuse_with is not None:
            return GoalStatus(
                proposal_id=proposal.proposal_id,
                request_id=proposal.request_id or "local",
                disposition=GoalDisposition.REJECTED,
                reason=self.refuse_with,
                admission_ref=None,
                current_disposition=ExecutionDisposition.NOT_STARTED,
            )
        self._counter += 1
        return GoalStatus(
            proposal_id=proposal.proposal_id,
            request_id=proposal.request_id or "local",
            disposition=GoalDisposition.ACCEPTED,
            reason=None,
            admission_ref=f"g{self._counter}",
            current_disposition=ExecutionDisposition.RUNNING,
        )

    def cancel(self, goal_id: str, expected_revision: int, idempotency_key: str) -> GoalStatus:
        self.cancel_calls.append((goal_id, expected_revision, idempotency_key))
        return GoalStatus(
            proposal_id=idempotency_key,
            request_id=f"cancel-{idempotency_key}",
            disposition=GoalDisposition.CANCELLED,
            reason=None,
            admission_ref=goal_id,
            current_disposition=ExecutionDisposition.CANCELLED,
        )

    def status(self, goal_id: str) -> ExecutionStatus:
        return ExecutionStatus(
            goal_ref=goal_id,
            certificate_ref=None,
            command_ref=None,
            disposition=ExecutionDisposition.RUNNING,
            evidence=(),
            reasons=(),
            horizon_s=None,
            capabilities=(),
        )

    def invalidate_queued(self, goal_id: str) -> int:
        self.invalidations[goal_id] = self.invalidations.get(goal_id, 0) + self.queued_samples
        return self.invalidations[goal_id]


