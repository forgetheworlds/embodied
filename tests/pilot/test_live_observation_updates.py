def test_pilot_probe_with_a_fake_transport_records_its_checks_and_no_credentials(tmp_path):
    import embodied.pilot.probe as probe

    config_path = _probe_config(tmp_path, max_calls=3, spend_ceiling_usd=1.0)
    config = probe.load_runtime_config(config_path)
    assert probe.probe_limits(config) == (3, 1.0)

    tool_call = {
        "type": "function",
        "function": {"name": "status", "arguments": '{"goal_id": "g1"}'},
    }
    transport = ScriptedTransport()
    transport.schedule(
        ScriptedReply(
            delay_s=0.4,
            document={"choices": [{"message": {"content": "the marker is red, upper right"}}]},
            usage={"total_tokens": 120},
        ),
        ScriptedReply(
            delay_s=0.3,
            document={"choices": [{"message": {"content": "ok", "tool_calls": [tool_call]}}]},
        ),
        ScriptedReply(
            delay_s=0.2,
            document={"choices": [{"message": {"content": "not json at all"}}]},
        ),
    )
    report = probe.execute_probe(config, FIXTURES / "observation.json", transport, max_calls=3)

    assert report.calls == 3
    assert report.image_ok and report.tools_ok
    checks = {check.name: check for check in report.checks}
    assert checks["image_support"].passed and "chars" in checks["image_support"].detail
    assert checks["tool_support"].passed and "status" in checks["tool_support"].detail
    assert checks["error_handling"].passed
    # Latency is recorded per call (including the malformed one), and the
    # round trip is labelled unseparated.
    assert len(report.latency) == 3
    assert all(record["round_trip_unseparated"] is True for record in report.latency)
    assert report.latency[0]["usage"] == {"total_tokens": 120}
    # The image really travelled: the transport saw a base64 data URI.
    first_document = transport.sent_documents[0]
    parts = first_document["messages"][0]["content"]
    assert any(
        part.get("image_url", {}).get("url", "").startswith("data:image/ppm;base64,")
        for part in parts
    )
    # No credential text is anywhere in the recorded output.
    rendered = json.dumps({"checks": [check.detail for check in report.checks], "latency": report.latency})
    assert "sk-" not in rendered and "Bearer" not in rendered
