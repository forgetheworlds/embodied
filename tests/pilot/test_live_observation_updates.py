# Scenario, all stamps in seconds (one clock domain; the recorder enforces
# non-decreasing order at write time):
#
#   1.00  mission recorded
#   1.05  obs-0 captured 1.00 — fresh; G1 (P1) admitted on sel-0
#   1.50  execution g1 running
#   2.00  req-1 sent (deadline 6.0)
#   2.45  obs-1 captured 2.40 — fresh, new target visible
#   2.50  req-2 sent, urgent: req-1 marked obsolete
#   3.00  req-2's reply: P2 admitted (g2 supersedes g1, queued invalidated);
#         the reply carried P2 twice — the repeat is idempotent, no second
#         admission
#   3.50  req-3 sent; 4.00 its reply proposes P2's id under a different
#         fingerprint — conflict, rejected
#   4.60  req-1's late reply (P1b) lands after req-2 superseded it —
#         reordered: recorded with the dead request named, not applied
#   5.00  req-4 sent (deadline 9.0)
#   8.00  obs-2 captured 0.20 but delivered 7.8s late — stale at arrival,
#         recorded with its age, never treated as current
#   9.40  req-4's reply lands 4.4s after send — delayed: expired, the delay is
#         recorded and never zeroed
#   9.60  req-5 sent; 10.00 its reply proposes P5 grounded on stale obs-2 —
#         rejected: a fresh goal is not grounded on stale evidence
#  12.00  req-6 sent, no scripted reply — silence
#  16.20  req-6 expires at tick; g2 continues within lease, reason recorded
#  16.40  cancel g2 with wrong expected revision — rejected
#  16.60  cancel g2 at its revision — cancelled, only g2
#  16.80  the same cancel key repeated — idempotent, same disposition


def build_delayed_replies_episode(episode_dir: Path) -> dict:
    """Drive the real broker, the shared scripted transport and the real
    Recorder through the scenario. Returns the closed manifest."""
    recorder = Recorder(episode_dir)
    log: list[tuple[str, dict, ClockStamp]] = []

    def sink(kind, payload, stamp, sim_time_s=None):
        log.append((kind, payload, stamp))

    seam = SeamFixture()
    transport = ScriptedTransport()
    provider = Provider(
        ModelConfig(
            provider="opencode-go",
            id=MODEL_IDENTITY,
            base_url="https://opencode.ai/zen/go/v1",
            api="openai-completions",
            image_transport="base64",
        ),
        transport,
        TOOL_SCHEMAS,
    )
    broker = PilotBroker(seam, parameters(), provider, host_id=HOST, clock_id=CLOCK, sink=sink)

    def ppm(marker_shift: int) -> bytes:
        rows = []
        for y in range(12):
            row = []
            for x in range(16):
                if marker_shift <= x <= marker_shift + 2 and 4 <= y <= 6:
                    row.append("220 30 30")
                else:
                    row.append(f"{40 + 6 * x} {60 + 4 * y} 90")
            rows.append("\n".join(row))
        return "P3\n16 12\n255\n".encode() + ("\n".join(rows) + "\n").encode()

    payloads = {
        "obs-0-left.ppm": ppm(10),
        "obs-0-right.ppm": ppm(8),
        "obs-1-left.ppm": ppm(4),
        "obs-1-right.ppm": ppm(2),
        "obs-2-left.ppm": ppm(10),
        "obs-2-right.ppm": ppm(8),
    }
    for name, data in payloads.items():
        recorder.write_payload(name, data)

    def harness(kind: str, payload, stamp: ClockStamp) -> None:
        log.append((kind, to_dict(payload), stamp))

    def drain() -> None:
        while log:
            kind, payload, stamp = log.pop(0)
            recorder.record(kind, payload, stamp)

    transport.schedule(
        ScriptedReply(delay_s=2.6, document=reply_document(
            (make_proposal("P1b", "req-1", "fp-P1b", 1, ("sel-0",), "explore"),))),
        ScriptedReply(delay_s=0.5, document=reply_document(
            (make_proposal("P2", "req-2", "fp-P2", 1, ("sel-1",)),
             make_proposal("P2", "req-2", "fp-P2", 1, ("sel-1",))))),
        ScriptedReply(delay_s=0.5, document=reply_document(
            (make_proposal("P2", "req-3", "fp-P2-conflict", 2, ("sel-1",)),))),
        ScriptedReply(delay_s=4.4, document=reply_document(
            (make_proposal("P4", "req-4", "fp-P4", 2, ("sel-1",), "explore"),))),
        ScriptedReply(delay_s=0.4, document=reply_document(
            (make_proposal("P5", "req-5", "fp-P5", 2, ("sel-2",)),))),
    )

    broker.set_mission(mission_contract(), S(1.00))
    drain()

    obs0 = make_observation("obs-0", 0, 1_000_000_000, 1_050_000_000, left_payload="obs-0-left.ppm")
    harness("observation", obs0, S(1.05))
    assert broker.on_observation(obs0, S(1.05)).fresh
    sel0 = make_selection("sel-0", "obs-0")
    harness("selection", sel0, S(1.10))
    broker.register_selection(sel0)
    broker.set_goal(make_proposal("P1", "local-initial", "fp-P1", 0, ("sel-0",), "explore"), S(1.20))
    drain()
    harness("execution", _execution("g1", "running"), S(1.50))
    drain()

    def packet(request: DecisionRequest) -> RequestPacket:
        return RequestPacket(
            request=request,
            mission_instruction=mission_contract().instruction,
            target_refs=(),
        )

    broker.submit(make_request("req-1", 0, 1, ("obs-0",)), packet(make_request("req-1", 0, 1, ("obs-0",))), S(2.00))
    drain()

    obs1 = make_observation("obs-1", 1, 2_400_000_000, 2_450_000_000, left_payload="obs-1-left.ppm")
    harness("observation", obs1, S(2.45))
    assert broker.on_observation(obs1, S(2.45)).fresh
    sel1 = make_selection("sel-1", "obs-1")
    harness("selection", sel1, S(2.48))
    broker.register_selection(sel1)
    request2 = make_request("req-2", 1, 1, ("obs-1",))
    broker.submit(request2, packet(request2), S(2.50), supersede_outstanding=True)
    drain()

    broker.poll(S(3.00))
    drain()
    harness("execution", _execution("g2", "running"), S(3.20))
    drain()

    request3 = make_request("req-3", 2, 2, ("obs-1",))
    broker.submit(request3, packet(request3), S(3.50))
    drain()
    broker.poll(S(4.00))
    drain()
    harness("execution", _execution("g2", "running"), S(4.20))
    drain()

    broker.poll(S(4.60))
    drain()
    harness("execution", _execution("g2", "running"), S(4.80))
    drain()

    request4 = make_request("req-4", 3, 2, ("obs-1",))
    broker.submit(request4, packet(request4), S(5.00))
    drain()

    obs2 = make_observation("obs-2", 2, 200_000_000, 8_000_000_000, left_payload="obs-2-left.ppm")
    harness("observation", obs2, S(8.00))
    stale_age = broker.on_observation(obs2, S(8.00))
    assert not stale_age.fresh and stale_age.age_s > 6.0
    sel2 = make_selection("sel-2", "obs-2")
    harness("selection", sel2, S(8.10))
    broker.register_selection(sel2)
    harness("execution", _execution("g2", "running"), S(8.20))
    drain()

    broker.poll(S(9.40))
    drain()
    request5 = make_request("req-5", 4, 2, ("obs-1",))
    broker.submit(request5, packet(request5), S(9.60))
    drain()
    broker.poll(S(10.00))
    drain()

    request6 = make_request("req-6", 5, 2, ("obs-1",))
    broker.submit(request6, packet(request6), S(12.00))
    drain()

    broker.tick(S(16.20))
    drain()
    broker.cancel("g2", 99, "cancel-wrong-1", S(16.40))
    drain()
    broker.cancel("g2", 2, "cancel-right-1", S(16.60))
    drain()
    broker.cancel("g2", 2, "cancel-right-1", S(16.80))
    drain()

    manifest = recorder.close(
        RunManifest(
            episode_id="delayed-replies-001",
            episode_kind="synthetic-fixture",
            arm="B2",
            sensor_mode=SensorMode.SIMULATOR_INTERFACE,
            model_identity=f"{MODEL_IDENTITY} (scripted replies; no live provider call)",
        )
    )
    return manifest_to_dict(manifest)


