def test_local_loop_continues_while_a_request_is_outstanding():
    seam = SeamFixture()
    transport = ScriptedTransport()  # schedules nothing: silence
    provider = Provider(
        ModelConfig("opencode-go", MODEL_IDENTITY, "https://x", "openai-completions", "base64"),
        transport,
        TOOL_SCHEMAS,
    )
    broker = PilotBroker(seam, parameters(), provider, host_id=HOST, clock_id=CLOCK)
    broker.set_mission(mission_contract(), S(1.0))
    request = make_request("req-silent", 0, 0, ())
    broker.submit(
        request,
        RequestPacket(request=request, mission_instruction="m"),
        S(2.0),
    )
    execution_stamps = []
    for step in range(3):
        now = S(2.5 + step)
        observation = _fresh_observation_at(f"obs-{step}", 2.4 + step * 0.1, 2.5 + step)
        broker.on_observation(observation, now)
        broker.tick(now)
        assert broker.poll(now) == ()
        execution_stamps.append(now)
    # The whole loop ran in logical time while the request stayed outstanding.
    assert broker.outstanding_request is not None
    assert broker.outstanding_request.request_id == "req-silent"
    assert [stamp.monotonic_ns for stamp in execution_stamps] == [
        S(2.5).monotonic_ns,
        S(3.5).monotonic_ns,
        S(4.5).monotonic_ns,
    ]


