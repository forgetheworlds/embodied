def test_cancel_with_the_wrong_revision_is_rejected_and_the_right_one_cancels_only_that_goal():
    broker, seam = _broker()
    broker.set_mission(mission_contract(), S(1.0))
    broker.set_goal(make_proposal("P1", "local", "fp-P1", 0, ("sel-0",), "explore"), S(1.2))
    broker.set_goal(make_proposal("P2", "local-2", "fp-P2", 1, ("sel-1",)), S(1.4))
    assert broker.active_goal_id == "g2"

    wrong = broker.cancel("g2", 99, "cancel-a", S(2.0))
    assert wrong.status.disposition is GoalDisposition.REJECTED
    assert "revision_mismatch" in wrong.status.reason
    assert seam.cancel_calls == []
    assert broker.active_goal_id == "g2"

    right = broker.cancel("g2", 2, "cancel-b", S(2.2))
    assert right.status.disposition is GoalDisposition.CANCELLED
    assert seam.cancel_calls == [("g2", 2, "cancel-b")]
    assert broker.active_goal_id is None  # only g2 was the active goal
    # g1's disposition is cancelled because g2 superseded it, and no cancel
    # call ever named it.
    assert len(seam.cancel_calls) == 1
    assert all(goal_id != "g1" for goal_id, _, _ in seam.cancel_calls)

    repeat = broker.cancel("g2", 2, "cancel-b", S(2.4))
    assert repeat.status.disposition is GoalDisposition.CANCELLED
    assert len(seam.cancel_calls) == 1  # the repeat never reached the seam


