class RecordingProvider(Provider):
    """Counts constructed instances, so 'B0 makes no provider' is measured."""

    constructions = 0

    def __init__(self, *args, **kwargs) -> None:
        type(self).constructions += 1
        super().__init__(*args, **kwargs)


def test_b1_makes_exactly_one_call_and_its_recipe_continues_past_the_first_waypoint():
    document = reply_document(())
    document["choices"][0]["message"]["content"] = json.dumps(
        {
            "mission_recipe": {
                "steps": [
                    {"action": "explore", "target_kind": "frontier", "target_ref": "next_unvisited",
                     "guard_kind": "always", "max_attempts": 1},
                    {"action": "inspect", "target_kind": "candidate", "target_ref": "next_uninspected",
                     "guard_kind": "candidate_present", "max_attempts": 3},
                    {"action": "return", "target_kind": "place", "target_ref": "start",
                     "max_attempts": 1},
                ],
                "bounds": {"max_steps": 6, "resource_ceiling": 8.0},
            }
        }
    )
    transport = ScriptedTransport()
    transport.schedule(ScriptedReply(delay_s=0.5, document=document))
    RecordingProvider.constructions = 0
    provider = RecordingProvider(_model_config(), transport, TOOL_SCHEMAS)
    assert RecordingProvider.constructions == 1

    broker, seam = _broker(provider=provider)
    broker.set_mission(mission_contract(), S(1.0))
    executive = B1OneShot(provider=provider)
    request = make_request("req-b1", 0, 0, ())
    executive.initial_request(
        broker, request, RequestPacket(request=request, mission_instruction="m"), S(2.0)
    )
    outcomes = broker.poll(S(3.0))
    parsed = next(outcome.parsed for outcome in outcomes if outcome.parsed is not None)
    recipe = executive.recipe_from_reply(parsed)
    assert recipe.source == "B1-one-shot"

    world = ScriptedWorld(candidates_after={1: ("c1",)}, blocked_for_reports={"c1": 1})
    result = _runner(broker, world, start_s=3.0).run(recipe)

    assert result.status == "completed"
    assert [step.action for step in result.steps] == ["explore", "inspect", "return"]
    inspect = next(step for step in result.steps if step.action == "inspect")
    assert inspect.attempts >= 2, "the declared retry after a blocked step did not happen"
    assert inspect.target_ref == "c1", "the target was not resolved from later local evidence"
    assert len(transport.sent_documents) == 1, "B1 made more than its one initial call"
    assert len(seam.admit_calls) == 3, "the recipe did not act past its first waypoint"

    with pytest.raises(OneShotBudgetSpent):
        executive.initial_request(
            broker, make_request("req-b1b", 1, 0, ()),
            RequestPacket(request=request, mission_instruction="m"), S(9.0),
        )


def test_b2_keeps_one_effective_request_and_applies_a_mid_flight_revision():
    transport = ScriptedTransport()
    transport.schedule(
        # The first request's reply is late and finds its request obsolete.
        ScriptedReply(delay_s=5.0, document=reply_document(
            (make_proposal("P-late", "req-1", "fp-late", 1, ("sel-0",)),))),
        # The replacement's reply is timely and carries a valid revision.
        ScriptedReply(delay_s=0.5, document=reply_document(
            (make_proposal("P-rev", "req-2", "fp-rev", 1, ("sel-0",)),))),
    )
    broker, seam = _broker(provider=Provider(_model_config(), transport, TOOL_SCHEMAS))
    broker.set_mission(mission_contract(), S(1.0))
    broker.set_goal(make_proposal("P1", "local", "fp-P1", 0, ("sel-0",), "explore"), S(1.2))
    observation = make_observation("obs-1", 1, 2_000_000_000, 2_050_000_000)
    broker.on_observation(observation, S(2.05))
    broker.register_selection(make_selection("sel-0", "obs-1"))

    engine = DecisionEngine(parameters(), MODEL_IDENTITY)
    executive = B2Continuous(provider=broker.provider, engine=engine)

    def packet_builder(decision):
        return RequestPacket(
            request=decision.request, mission_instruction="m",
            target_refs=decision.cited_observation_ids,
        )

    from embodied.pilot.decisions import SceneStatus

    executive.tick(broker, SceneStatus(signature=0.9, new_targets=("c1",)), packet_builder, S(3.0))
    assert broker.outstanding_request.request_id.startswith("req-")
    first = broker.outstanding_request.request_id
    outstanding_now = [
        record.request.request_id for record in broker.requests.values()
        if record.state == "outstanding"
    ]
    assert outstanding_now == [first], "more than one effective request is outstanding"

    # An urgent scene supersedes the first request: the replacement is the
    # second request and the first is not applied.
    executive.tick(broker, SceneStatus(signature=0.9, map_conflict=True), packet_builder, S(3.5))
    assert broker.requests[first].state == "obsolete"
    second = broker.outstanding_request.request_id
    assert second != first
    assert [
        record.request.request_id for record in broker.requests.values()
        if record.state == "outstanding"
    ] == [second]

    executive.tick(broker, SceneStatus(signature=0.9), packet_builder, S(4.2))
    assert broker.active_goal_id == "g2", "the admitted revision was not applied"
    assert broker.active_revision == 2
    assert seam.invalidations.get("g1") == seam.queued_samples
    # The superseded request's late reply was discarded without a second movement.
    executive.tick(broker, SceneStatus(signature=0.9), packet_builder, S(8.6))
    assert broker.active_goal_id == "g2"
    assert broker.active_revision == 2


