def test_valid_revision_during_an_active_goal_supersedes_and_invalidates_queued_samples():
    transport = ScriptedTransport()
    transport.schedule(
        ScriptedReply(delay_s=0.5, document=reply_document(
            (make_proposal("P2", "req-1", "fp-P2", 1, ("sel-1",)),))),
    )
    broker, seam = _broker(provider=Provider(_model_config(), transport, TOOL_SCHEMAS))
    broker.set_mission(mission_contract(), S(1.0))
    broker.set_goal(make_proposal("P1", "local", "fp-P1", 0, ("sel-0",), "explore"), S(1.2))
    assert broker.active_goal_id == "g1" and broker.active_revision == 1

    observation = make_observation("obs-1", 1, 2_000_000_000, 2_050_000_000)
    broker.on_observation(observation, S(2.05))
    broker.register_selection(make_selection("sel-1", "obs-1"))
    request = make_request("req-1", 0, 1, ("obs-1",))
    broker.submit(request, RequestPacket(request=request, mission_instruction="m"), S(2.5))
    outcomes = broker.poll(S(3.0))

    assert broker.active_goal_id == "g2" and broker.active_revision == 2
    assert seam.invalidations["g1"] == seam.queued_samples  # invalidated atomically
    supersede = [
        outcome for outcome in outcomes
        if outcome.status is not None
        and outcome.status.disposition is GoalDisposition.SUPERSEDED
    ]
    assert supersede and "queued samples invalidated" in supersede[0].status.reason

    # The same revision, arriving again, is stale: an older reply cannot
    # overwrite the newer accepted goal.
    stale = broker.process_proposal(make_proposal("P3", "req-1", "fp-P3", 1, ("sel-1",)), S(4.0))
    assert stale.status.disposition is GoalDisposition.REJECTED
    assert "stale_revision" in stale.status.reason
    assert broker.active_revision == 2


