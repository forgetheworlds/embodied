def test_requested_counts_are_never_copied_into_observed_counts():
    now = S(10.0)
    claims = assemble_claims(
        requested_counts={"red-kettle": 3, "blue-box": 1},
        observed_counts={"red-kettle": 1},
        support_refs={"red-kettle": ("obs-1",)},
        now=now,
    )
    by_target = {claim.target: claim for claim in claims}
    kettle = by_target["red-kettle"]
    assert kettle.observed == 1 and kettle.kind is ClaimKind.OBSERVATION
    assert "requested_count=3_observed=1" in kettle.unmet_requirements
    unsupported = by_target["blue-box"]
    assert unsupported.observed == 0
    assert unsupported.kind is ClaimKind.INFERENCE
    assert "no supporting observation" in unsupported.unmet_requirements

    report = build_final_report(
        requested_counts={"red-kettle": 3},
        observed_counts={"red-kettle": 1},
        support_refs={"red-kettle": ("obs-1",)},
        termination_reason="bounds_exhausted",
        mission_revision=0,
        now=now,
    )
    assert report.claims[0].observed == 1
    assert report.unmet_requirements == ("requested_count=3_observed=1",)
    assert report.termination_reason == "bounds_exhausted"


