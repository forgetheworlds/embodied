class ScriptedWorld:
    """A permitted-evidence world: candidates appear only after movement, and
    a route can be blocked until a local step clears it."""

    def __init__(
        self,
        candidates_after: dict[int, tuple[str, ...]],
        frontiers: tuple[str, ...] = ("f1",),
        blocked_for_reports: dict[str, int] | None = None,
        budget_s: float = 60.0,
    ) -> None:
        self.candidates_after = candidates_after
        self.frontiers = frontiers
        # How many blocked reports a route survives before the local replanner
        # clears it. Modelling it in reports rather than in steps is what lets
        # a declared retry make progress.
        self.blocked_for_reports = blocked_for_reports or {}
        self.block_reports: dict[str, int] = {}
        self.budget_s = budget_s
        self.steps = 0
        self.consumed_s = 0.0
        self._observations = 0

    def discovered_candidates(self) -> tuple[str, ...]:
        found: tuple[str, ...] = ()
        for threshold, names in sorted(self.candidates_after.items()):
            if self.steps >= threshold:
                found = tuple(sorted(set(found) | set(names)))
        return found

    def known_frontiers(self) -> tuple[str, ...]:
        return self.frontiers

    def start_place(self) -> str:
        return "start"

    def is_blocked(self, target_ref: str) -> bool:
        remaining = self.blocked_for_reports.get(target_ref)
        if remaining is None:
            return False
        reports = self.block_reports.get(target_ref, 0)
        self.block_reports[target_ref] = reports + 1
        return reports < remaining

    def budget_remaining_s(self) -> float:
        return self.budget_s - self.consumed_s

    def step(self, action: str, target_ref: str | None) -> tuple[Observation, ...]:
        self.steps += 1
        self.consumed_s += 1.0
        self._observations += 1
        return (
            make_observation(
                f"obs-{self._observations}", self._observations,
                1_000_000_000 + self._observations * 1_000_000,
                1_000_500_000 + self._observations * 1_000_000,
                episode_id="executive-check",
            ),
        )

    def completion(self, action: str, target_ref: str | None) -> tuple[str, tuple[str, ...]]:
        return "achieved", (f"obs-{self._observations}",)


def _runner(broker: PilotBroker, world, start_s: float = 1.0):
    clock = {"ns": int(start_s * 1e9)}

    def now() -> ClockStamp:
        clock["ns"] += 100_000_000
        return ClockStamp(HOST, CLOCK, clock["ns"])

    runner = RecipeRunner(broker, world, now, sink=broker.sink)
    return runner


